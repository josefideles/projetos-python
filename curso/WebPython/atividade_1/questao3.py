'''Faça um programa que leia duas notas de um aluno
 e mostre a sua média na tela.'''

nota1 = float(input('Digite a sua nota: \n Obs! Se for uma nota decimal, utilize "." no lugar da "," : '))
nota2 = float(input('Digite outra nota: \n Obs! Se for uma nota decimal, utilize "." no lugar da "," : '))

media = (nota1+nota2)/2

print('Sua média das duas notas foi: ', media)