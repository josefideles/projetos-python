num = int(input('Digite um número ente 1 e 7: '))
if num>7 or num<1:
    print('Não existe dia na semana com esse número')
elif num==1:
    print("Esse número corresponde a DOMINGO")
elif num==2:
    print('Esse número corresponde a SEGUNDA-FEIRA')
elif num==3:
    print('Esse número corresponde a TERÇA-FEIRA')
elif num==4:
    print('Esse número corresponde a QUARTA-FEIRA')
elif num==5:
    print('Esse numero corresponde a QUINTA-FEIRA')
elif num==6:
    print('Esse numero corresponde a SEXTA-FEIRA')
else:
    print('Esse numero corresponde a SABADO')



